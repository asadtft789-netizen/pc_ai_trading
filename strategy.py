"""Base strategy class for the self-evolving trader.

Strategies are generated by the LLM and must adhere to this interface.
"""

from abc import ABC, abstractmethod
import pandas as pd
from typing import Dict, Any, List


class BaseStrategy(ABC):
    """
    Abstract base class for all trading strategies.

    The LLM will subclass this and implement the 'generate_signals' method.
    """

    def __init__(self, name: str, params: Dict[str, Any] = None):
        self.name = name
        self.params = params or {}

    @abstractmethod
    def generate_signals(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Processes historical data and returns a DataFrame with signals.

        Args:
            df: DataFrame with multi-index (timestamp, symbol) and columns [open, high, low, close, volume]

        Returns:
            A DataFrame with the same index as 'df' and a 'signal' column.
            Signal values: 1 (buy/long), -1 (sell/short), 0 (neutral/flat).
        """
        pass

    def __repr__(self):
        return f"Strategy({self.name}, params={self.params})"

"""Strategy Executor for the self-evolving trader.

Converts signals generated by strategies into orders on the Alpaca API.
Includes position management, exit rules (stop-loss / take-profit / max hold),
and reconciliation of fills against the trade database.
"""

import logging
import time
from typing import Any, Dict, List, Optional, Tuple
import pandas as pd
from alpaca.trading.client import TradingClient
from alpaca.trading.requests import MarketOrderRequest, GetOrdersRequest
from alpaca.trading.enums import OrderSide, TimeInForce, QueryOrderStatus

from config import Settings
from risk_engine import RiskEngine

logger = logging.getLogger(__name__)


class StrategyExecutor:
    """Executes trades on Alpaca based on signals."""

    def __init__(self, settings: Settings, risk_engine: RiskEngine):
        self.settings = settings
        self.risk_engine = risk_engine
        self.trading_client = TradingClient(
            settings.alpaca.api_key,
            settings.alpaca.api_secret,
            paper=True
        )

    def sync_positions(self, signals: Dict[str, int]) -> List[Dict[str, Any]]:
        """
        Synchronizes current portfolio positions with the target signals.
        signals: Dictionary mapping symbol -> signal (1, -1, or 0).
        Returns a list of trade events for logging.
        """
        events: List[Dict[str, Any]] = []
        try:
            positions = {p.symbol: p for p in self.trading_client.get_all_positions()}

            for symbol, signal in signals.items():
                current_pos = positions.get(symbol)

                if signal == 0:
                    if current_pos:
                        events.append({
                            "type": "close",
                            "symbol": symbol,
                            "side": current_pos.side,
                            "qty": float(current_pos.qty),
                            "price": float(current_pos.avg_entry_price) if getattr(current_pos, 'avg_entry_price', None) else 0.0,
                            "pnl": float(getattr(current_pos, 'unrealized_pl', 0) or 0),
                        })
                        self._close_position(symbol)
                elif signal == 1:
                    if not current_pos or float(current_pos.qty) <= 0:
                        order = self._open_position(symbol, OrderSide.BUY)
                        events.append(self._order_to_event(order, "open", symbol, "buy"))
                elif signal == -1:
                    if not current_pos or float(current_pos.qty) >= 0:
                        order = self._open_position(symbol, OrderSide.SELL)
                        events.append(self._order_to_event(order, "open", symbol, "sell"))

        except Exception as e:
            logger.error(f"Error syncing positions: {e}")

        return events

    def _order_to_event(self, order: Optional[Any], event_type: str, symbol: str, side: str) -> Dict[str, Any]:
        if order is None:
            return {
                "type": event_type,
                "symbol": symbol,
                "side": side,
                "qty": 0.0,
                "price": 0.0,
                "order_id": None,
            }
        return {
            "type": event_type,
            "symbol": symbol,
            "side": side,
            "qty": float(getattr(order, 'qty', 0) or 0),
            "price": float(getattr(order, 'filled_avg_price', 0) or 0),
            "order_id": str(getattr(order, 'id', '')),
        }

    def _close_position(self, symbol: str):
        """Liquidates a position for a specific symbol."""
        logger.info(f"Closing position for {symbol}")
        try:
            self.trading_client.close_position(symbol)
        except Exception as e:
            logger.error(f"Failed to close position for {symbol}: {e}")

    def _open_position(self, symbol: str, side: OrderSide) -> Optional[Any]:
        """Opens a new position based on risk engine constraints."""
        order_size_usd = self.settings.risk.max_order_size_usd

        if not self.risk_engine.validate_trade(order_size_usd):
            logger.warning(f"Trade validation failed for {symbol} at ${order_size_usd}")
            return None

        logger.info(f"Opening {side} position for {symbol} (approx ${order_size_usd})")

        try:
            order_data = MarketOrderRequest(
                symbol=symbol,
                notional=order_size_usd,
                side=side,
                time_in_force=TimeInForce.DAY
            )
            order = self.trading_client.submit_order(order_data)
        except Exception as e:
            logger.error(f"Failed to open position for {symbol}: {e}")
            return None
        return order

    def check_exits(
        self,
        open_trades: List[Dict[str, Any]],
        latest_prices: Dict[str, float],
        trade_opened_at: Dict[str, float],
        max_hold_seconds: int = 7 * 86400,
        stop_loss_pct: float = 0.05,
        take_profit_pct: float = 0.10,
    ) -> List[Dict[str, Any]]:
        """
        Checks open positions against exit rules: stop-loss, take-profit, max hold.
        Returns a list of close events {symbol, side, qty, price, pnl, reason}.
        """
        close_events: List[Dict[str, Any]] = []
        now = time.time()

        for trade in open_trades:
            symbol = trade['symbol']
            price = latest_prices.get(symbol)
            if price is None:
                continue

            entry_price = trade.get('entry_price') or 0.0
            side = trade.get('side', '').lower()
            qty = float(trade.get('qty', 0))
            opened_at = trade_opened_at.get(symbol, now)

            # Compute unrealized PnL % from entry
            if entry_price <= 0:
                continue
            if side == 'buy':
                pnl_pct = (price - entry_price) / entry_price
            else:
                pnl_pct = (entry_price - price) / entry_price

            reason: Optional[str] = None
            if pnl_pct <= -stop_loss_pct:
                reason = f"stop-loss ({pnl_pct:.2%})"
            elif pnl_pct >= take_profit_pct:
                reason = f"take-profit ({pnl_pct:.2%})"
            elif (now - opened_at) > max_hold_seconds:
                reason = f"max-hold ({int((now - opened_at) / 86400)} days)"

            if reason:
                close_events.append({
                    "symbol": symbol,
                    "side": side,
                    "qty": qty,
                    "price": price,
                    "pnl": (price - entry_price) * qty if side == 'buy' else (entry_price - price) * qty,
                    "reason": reason,
                })
                logger.info(
                    f"EXIT {symbol} {side} qty={qty} price={price:.2f} pnl_pct={pnl_pct:.2%} reason={reason}"
                )

        return close_events

    def reconcile_trades(
        self,
        open_trades: List[Dict[str, Any]],
        latest_prices: Dict[str, float],
    ) -> List[Dict[str, Any]]:
        """
        Reconciles DB open trades with current Alpaca positions.
        Marks a trade filled if Alpaca reports no open position for its symbol.
        Returns updated trade records with current prices and unrealized PnL.
        """
        try:
            positions = {p.symbol: p for p in self.trading_client.get_all_positions()}
        except Exception as e:
            logger.error(f"Error fetching positions for reconciliation: {e}")
            positions = {}

        updated: List[Dict[str, Any]] = []
        for trade in open_trades:
            symbol = trade['symbol']
            pos = positions.get(symbol)
            if pos is None:
                # Alpaca reports no position: mark closed at last known price
                price = latest_prices.get(symbol) or trade.get('entry_price') or 0.0
                entry_price = trade.get('entry_price') or 0.0
                side = trade.get('side', '').lower()
                qty = float(trade.get('qty', 0))
                pnl = (price - entry_price) * qty if side == 'buy' else (entry_price - price) * qty
                updated.append({**trade, 'price': price, 'pnl': pnl, 'status': 'filled'})
            else:
                price = float(getattr(pos, 'current_price', 0) or 0)
                updated.append({**trade, 'price': price, 'pnl': float(getattr(pos, 'unrealized_pl', 0) or 0), 'status': 'open'})

        return updated

    def get_active_orders(self) -> List[Any]:
        """Returns currently open orders."""
        req = GetOrdersRequest(status=QueryOrderStatus.OPEN)
        return self.trading_client.get_orders(req)
